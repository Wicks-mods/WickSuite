"""Turn the minimap's terrain tiles into Wick's Map's data file.

The game draws the minimap from one 256 pixel image per map tile (533 1/3
yards a side), world/minimaps/<continent>/mapXX_YY.blp, with XX counting
columns east and YY rows south across a 64 by 64 grid. Wick's Map draws
the same images under the world map's pins when you zoom in past the
painted map's detail. Addons can only reach them by file id, so this
reads the ids from wow.export's cached copy of the community listfile and
writes them out by continent.

Only ids go into the addon, as runs: a column, its first row, how many
rows in a row follow, and the first of their ids (the ids of a column's
consecutive rows are consecutive). The images themselves stay in the game.

    python WickSuite/tools/map-tiles.py [listfile-pf-textures.dat]

Writes Tiles.lua into the WicksMap addon folder.
"""
import os
import re
import sys
import time

LISTFILE = os.path.join(os.environ.get("LOCALAPPDATA", ""), "wow.export", "User Data",
                        "Default", "casc", "listfile", "listfile-pf-textures.dat")
ADDON = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                      "..", "..", "WicksMap"))

# The instance id C_Map.GetWorldPosFromMapPos hands back, and the folder
# the game keeps that continent's minimap in.
CONTINENTS = [
    (0, "azeroth", "Eastern Kingdoms"),
    (1, "kalimdor", "Kalimdor"),
    (530, "expansion01", "Outland"),
]


def read_tiles(data, folder):
    """{(col, row): file id} for one continent. In wow.export's file each
    path is preceded by its id, four bytes big-endian."""
    pat = re.compile(rb"world/minimaps/" + folder.encode() + rb"/map(\d\d)_(\d\d)\.blp\x00")
    tiles = {}
    for m in pat.finditer(data):
        fid = int.from_bytes(data[m.start() - 4:m.start()], "big")
        tiles[(int(m.group(1)), int(m.group(2)))] = fid
    return tiles


def runs(tiles):
    out = []
    for col, row in sorted(tiles):
        fid = tiles[(col, row)]
        last = out[-1] if out else None
        if last and last[0] == col and last[1] + last[2] == row and last[3] + last[2] == fid:
            last[2] += 1
        else:
            out.append([col, row, 1, fid])
    return out


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else LISTFILE
    data = open(path, "rb").read()
    lines = [
        "-- Wick's Map",
        "-- Tiles.lua: the minimap's terrain tiles, by continent. Generated by",
        "-- WickSuite/tools/map-tiles.py from wow.export's listfile on %s; do not" % time.strftime("%Y-%m-%d"),
        "-- edit by hand. Each run is four numbers: a column of the 64 by 64 tile",
        "-- grid, its first row, how many rows follow it, and the file id of the",
        "-- first (the rest count up from it).",
        "",
        "local ADDON, ns = ...",
        "",
        "ns.TILE_RUNS = {",
    ]
    for cont, folder, name in CONTINENTS:
        tiles = read_tiles(data, folder)
        if not tiles:
            sys.exit("no tiles for %s in %s" % (folder, path))
        rs = runs(tiles)
        lines.append("    -- %s (world/minimaps/%s): %d tiles in %d runs" % (name, folder, len(tiles), len(rs)))
        lines.append("    [%d] = {" % cont)
        for i in range(0, len(rs), 4):
            lines.append("        " + " ".join("%d, %d, %d, %d," % tuple(r) for r in rs[i:i + 4]))
        lines.append("    },")
        print("%-17s %4d tiles, %3d runs" % (name, len(tiles), len(rs)))
    lines.append("}")
    lines.append("")
    out = os.path.join(ADDON, "Tiles.lua")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
